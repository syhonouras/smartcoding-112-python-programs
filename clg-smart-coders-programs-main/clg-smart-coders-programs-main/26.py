#26	Read a number (1–7) and print the corresponding day of the week	Resource Link

day  = int(input("Enter marks 0-100: "))

if day == 1 :
    print("monday")
elif day == 2:
    print("Tuesday")
elif  day == 3:
    print("Wednesday")
elif  day == 4:
    print("thursday")
elif  day == 5:
    print("friday")
elif  day == 6:
    print("saturday")
else:
    print("sunday")
